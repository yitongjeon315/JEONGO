function createSession(config) {
  return {
    id: config.id,
    title: `${config.id}회차: TOPIK II ${config.level} ${config.title}`,
    subTitle: config.subTitle,
    duration: "2시간 30분",
    ...(config.id === 4 ? { topikIntro: topikTwoIntro } : {}),
    timeline: createTimeline(config.level, config.title),
    vocabWarmUp: createWarmUp(config.level, config.vocabulary),
    vocabGamePairs: config.vocabulary.map((item, index) => ({
      type: "text-text",
      text: item.word,
      matchVal: item.symbol,
      key: `advanced-${config.id}-${index}`,
    })),
    prePractice: config.prePractice,
    practiceQuestions: [...config.questions, ...(expandedPracticeByLevel[config.level] || [])].map((question) => ({
      source: {
        kind: "자체 제작",
        basis: "국립국제교육원 TOPIK II PBT 문항 유형 참고",
        isOfficialPastExam: false,
        reviewed: "형식 검토 완료 · 난이도 통계 미검증",
      },
      ...question,
    })),
    vocabularyMastery: {
      title: `${config.level} 마무리 어휘 복습`,
      description: "오답 문항에서 확인한 단어를 자신의 문장으로 다시 써 보세요.",
      nouns: config.vocabulary.slice(0, 3).map((item) => ({ word: item.word, meaning: item.definition })),
      verbs: config.vocabulary.slice(3).map((item) => ({ word: item.word, meaning: item.definition })),
    },
  };
}

